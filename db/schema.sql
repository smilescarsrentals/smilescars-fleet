-- ============================================================================
--  SmilesCars — Supabase schema for the API in /api + /lib
--  Run once in the Supabase SQL editor (SQL Editor -> New query -> Run).
--
--  SAFE TO RE-RUN. Every statement is additive and idempotent:
--    * CREATE TABLE IF NOT EXISTS   — never touches a table that already exists
--    * ADD COLUMN IF NOT EXISTS     — never changes an existing column's type
--    * no DROP, no DELETE, no UPDATE of business data
--
--  Column types are dictated by the API's write coercion (lib/core.js): a
--  column listed there as numeric/timestamp receives NULL when the app clears
--  it; everything else stays text so a blank "" is always a legal value.
--
--  After running this, check the result with:  GET /api?action=health
-- ============================================================================

-- ── Fleet ───────────────────────────────────────────────────────────────────
