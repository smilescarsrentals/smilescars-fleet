-- ============================================================================
--  Tables that replace Google Drive / Script Properties
-- ============================================================================

-- ── Stored files: licence photos, signatures, agreement PDFs, backups ───────
-- Served back to the browser at /api?action=file&id=<id>.
CREATE TABLE IF NOT EXISTS files (
  id         text PRIMARY KEY,
  kind       text,            -- blacklist | signature | staff-signature | agreement | backup
  filename   text,
  mime_type  text,
  size_bytes integer,
  data       bytea NOT NULL,
  created_at timestamp,
  created_by text
);
CREATE INDEX IF NOT EXISTS files_kind_idx ON files (kind);

-- ── Rental agreements (was: the "Agreements" sheet + a Drive folder) ────────
CREATE TABLE IF NOT EXISTS agreements (
  ref        text,
  plate      text,
  client     text,
  staff_name text,
  timestamp  timestamp,
  drive_url  text,           -- kept as the column name so pre-migration rows still read
  file_id    text
);
ALTER TABLE agreements ADD COLUMN IF NOT EXISTS file_id   text;
ALTER TABLE agreements ADD COLUMN IF NOT EXISTS drive_url text;
CREATE INDEX IF NOT EXISTS agreements_ref_idx ON agreements (ref);

-- ── Client signature hand-off (was: Script Properties, 24h TTL) ─────────────
CREATE TABLE IF NOT EXISTS signature_tokens (
  token      text PRIMARY KEY,
  file_id    text,
  url        text,
  created_at timestamp
);

-- ── Staff signatures, one per staff member (was: Script Properties) ─────────
CREATE TABLE IF NOT EXISTS staff_signatures (
  staff_name text PRIMARY KEY,   -- stored lowercased
  file_id    text,
  url        text,
  updated_at timestamp
);

-- ── Export audit log (was: the "ExportLog" sheet) ───────────────────────────
CREATE TABLE IF NOT EXISTS export_log (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  timestamp   timestamp,
  staff_name  text,
  role        text,
  export_type text,
  row_count   integer,
  filters     text
);
