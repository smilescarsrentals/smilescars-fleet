ALTER TABLE fleet ADD COLUMN IF NOT EXISTS checked_out_by   text;
ALTER TABLE fleet ADD COLUMN IF NOT EXISTS booking_type     text;
ALTER TABLE fleet ADD COLUMN IF NOT EXISTS reg_card_url     text;
ALTER TABLE fleet ADD COLUMN IF NOT EXISTS photos_url       text;
ALTER TABLE fleet ADD COLUMN IF NOT EXISTS police_fine_out  numeric;
ALTER TABLE fleet ADD COLUMN IF NOT EXISTS parking_fine_out numeric;
ALTER TABLE fleet ADD COLUMN IF NOT EXISTS km_out           text;
ALTER TABLE fleet ADD COLUMN IF NOT EXISTS driver           text;

-- ── History ─────────────────────────────────────────────────────────────────
-- `id` gives the append-only log a stable newest-first order (the app used to
-- rely on sheet row position).
CREATE TABLE IF NOT EXISTS history (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  timestamp      timestamp,
  plate          text,
  type           text,
  action         text,
  client         text,
  client_phone   text,
  booked_from    timestamp,
  return_date    timestamp,
  location       text,
  remarks        text,
  staff_name     text,
  fuel_out       text,
  fuel_in        text,
  amount         numeric,
  currency       text,
  police_fine    numeric,
  parking_fine   text,
  garage         text,
  payment_status text,
  amount_paid    numeric,
  km_out         text,
  km_in          text,
  driver         text
);

-- If history came from the sheet export without a surrogate key, add one. On a
-- non-empty table Postgres backfills it in the table's existing physical order,
-- which for an append-only log is insertion order.
ALTER TABLE history ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX IF NOT EXISTS history_plate_idx      ON history (lower(btrim(plate)));
CREATE INDEX IF NOT EXISTS history_staff_name_idx ON history (lower(btrim(staff_name)));

-- ── Config (staff, locations, garages, drivers, fuel access) ────────────────
CREATE TABLE IF NOT EXISTS config (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type     text,
  value    text,
  password text,
  role     text,
  active   text
);

-- Staff activation, used by verifyStaff / getStaffList / setStaffActive.
ALTER TABLE config ADD COLUMN IF NOT EXISTS active   text;
ALTER TABLE config ADD COLUMN IF NOT EXISTS role     text;
ALTER TABLE config ADD COLUMN IF NOT EXISTS password text;
ALTER TABLE config ADD COLUMN IF NOT EXISTS id       bigint GENERATED BY DEFAULT AS IDENTITY;

-- Blank counts as active in code; this just makes it explicit.
UPDATE config SET active = 'TRUE' WHERE type = 'Staff' AND (active IS NULL OR active = '');

-- ── Settings ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS settings (
