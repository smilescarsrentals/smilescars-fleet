  fuel_out          text,
  amount            numeric,
  currency          text,
  garage            text,
  payment_status    text,
  amount_paid       numeric,
  police_fine_out   numeric,
  parking_fine_out  numeric,
  km_out            text,
  driver            text,
  reg_card_url      text,
  photos_url        text,
